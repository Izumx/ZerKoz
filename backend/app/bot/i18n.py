def t(lang: str, key: str, **kwargs) -> str:
    """Шаблоны в HTML-разметке Telegram: пользовательские значения экранирует вызывающий код."""
    text = TEXTS.get(lang, TEXTS["ru"]).get(key) or TEXTS["ru"][key]
    return text.format(**kwargs) if kwargs else text


def all_langs(key: str) -> set[str]:
    """Текст кнопки на всех языках — для фильтров хендлеров."""
    return {TEXTS[lang][key] for lang in TEXTS}


def fmt_dt(dt: datetime) -> str:
    return dt.astimezone(KZ_TZ).strftime("%d.%m.%Y %H:%M")


def stage(lang: str, code: str) -> tuple[str, str]:
    emoji, ru, kz = STAGES[code]
    return emoji, kz if lang == "kz" else ru


def signal_status(lang: str, code: str) -> tuple[str, str, str]:
    emoji, ru, kz, hint_ru, hint_kz = SIGNAL_STATUSES[code]
    return (emoji, kz, hint_kz) if lang == "kz" else (emoji, ru, hint_ru)
